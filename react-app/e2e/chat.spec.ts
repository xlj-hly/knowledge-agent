async function login(page: Page, username: string, password: string) {
  await page.getByLabel('用户名', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await expect(page.getByRole('navigation', { name: '主导航' })).toBeVisible()
}

async function chooseSetting(page: Page, label: string, option: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

async function expectChatFrame(page: Page) {
  await expect(page.locator('.topbar')).toBeVisible()
  await expect(page.locator('.page-footer')).toBeVisible()
  await expect(page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '对话', exact: true })).toHaveCSS('font-size', /^(?!0px)/)
  const card = await page.locator('.chat-workspace').boundingBox()
  const content = await page.locator('.main-content').boundingBox()
  const topbar = await page.locator('.topbar').boundingBox()
  if (!card || !content || !topbar) throw new Error('聊天页面缺少标准框架')
  expect(card.x).toBeGreaterThan(content.x)
  expect(card.x + card.width).toBeLessThan(content.x + content.width)
  expect(card.y).toBeGreaterThan(topbar.y + topbar.height)
  await expect(page.getByLabel('输入消息', { exact: true })).toBeEditable()
}

async function expectMessageSides(page: Page) {
  const user = page.locator('.chat-message.user').last()
  const assistant = page.locator('.chat-message.assistant').last()
  await expect(user).toBeVisible()
  await expect(assistant).toBeVisible()
  const userAvatar = await user.locator('.chat-message-avatar').boundingBox()
  const userContent = await user.locator('.chat-message-content').boundingBox()
  const assistantAvatar = await assistant.locator('.chat-message-avatar').boundingBox()
  const assistantContent = await assistant.locator('.chat-message-content').boundingBox()
  expect(userAvatar).not.toBeNull()
  expect(userContent).not.toBeNull()
  expect(assistantAvatar).not.toBeNull()
  expect(assistantContent).not.toBeNull()
  if (!userAvatar || !userContent || !assistantAvatar || !assistantContent) throw new Error('消息布局缺少可见内容')
  expect(userAvatar.x).toBeGreaterThan(userContent.x + userContent.width)
  expect(assistantAvatar.x + assistantAvatar.width).toBeLessThan(assistantContent.x)
  expect(userContent.x).toBeGreaterThan(assistantContent.x)
  const readingArea = await page.locator('.chat-message-list').boundingBox()
  expect(readingArea).not.toBeNull()
  if (!readingArea) throw new Error('消息阅读区不可见')
  for (const content of [userContent, assistantContent]) {
    expect(content.x).toBeGreaterThanOrEqual(readingArea.x)
    expect(content.x + content.width).toBeLessThanOrEqual(readingArea.x + readingArea.width + 1)
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}

