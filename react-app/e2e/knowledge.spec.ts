import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const password = 'Knowledge-admin-2026'
const origin = 'http://knowledge.localhost:5175'

async function login(page: Page, username: string, secret: string) {
  await page.getByLabel('用户名', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(secret)
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await expect(page.getByRole('navigation', { name: '主导航' })).toBeVisible()
}

test('知识库从真实页面导入、分块编辑、检索、刷新与删除', async ({ context }) => {
  test.setTimeout(120_000)
  const platform = await context.newPage()
  await platform.goto('http://platform.localhost:5175/platform/tenants')
  await login(platform, 'platform.root', 'Platform-pass-2026')
  await platform.getByRole('button', { name: '开通企业', exact: true }).click()
  const create = platform.getByRole('dialog')
  await create.getByLabel('企业名称', { exact: true }).fill('知识库流程验收企业')
  await create.getByLabel('访问域名', { exact: false }).fill('knowledge.localhost')
  await create.getByLabel('管理员用户名', { exact: false }).fill('knowledge.admin')
  await create.getByLabel('管理员初始密码', { exact: false }).fill(password)
  await create.getByRole('button', { name: '开通企业', exact: true }).click()
  await expect(create).not.toBeVisible()

  const page = await context.newPage()
  await page.goto(`${origin}/knowledge`)
  await login(page, 'knowledge.admin', password)
  await expect(page).toHaveURL(`${origin}/knowledge`)

  // 从实际页面配置连接；故障服务不会被当作成功，也不会使有效会话失效。
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '嵌入器 Embedder', exact: true }).click()
  await page.getByRole('button', { name: '添加模型', exact: true }).click()
  const connection = page.getByRole('dialog')
  await connection.getByLabel('配置名称', { exact: true }).fill('页面配置验收模型')
  await connection.getByLabel('服务地址', { exact: false }).fill('http://127.0.0.1:1/v1')
  await connection.getByLabel('模型名称', { exact: true }).fill('test-embedding')
  await connection.getByLabel('向量维度', { exact: true }).fill('3')
  await connection.getByLabel(/^API Key/).fill('e2e-only-key')
  await connection.getByRole('button', { name: '保存模型', exact: true }).click()
  await expect(connection).not.toBeVisible()
  const model = page.getByRole('row').filter({ hasText: '页面配置验收模型' })
  await expect(model).toContainText('已配置')
  await model.getByRole('button', { name: '编辑与测试', exact: true }).click()
  await expect(connection.getByLabel(/^API Key/)).toHaveValue('e2e-only-key')
  await connection.getByLabel(/^API Key/).fill('e2e-updated-key')
  await connection.getByRole('button', { name: '保存模型', exact: true }).click()
  await expect(connection).not.toBeVisible()
  await page.reload()
  await expect(model).toContainText('已配置')
  await model.getByRole('button', { name: '编辑与测试', exact: true }).click()
  await expect(connection.getByLabel(/^API Key/)).toHaveValue('e2e-updated-key')
  await connection.getByLabel(/^API Key/).fill('')
  await connection.getByRole('button', { name: '保存模型', exact: true }).click()
  await expect(connection).not.toBeVisible()
  await expect(model).toContainText('未配置')
  await model.getByRole('button', { name: '编辑与测试', exact: true }).click()
  await expect(connection.getByLabel(/^API Key/)).toHaveValue('')
  await connection.getByRole('button', { name: '测试调用并检测维度', exact: true }).click()
  await expect(connection.getByRole('alert')).toBeVisible()
  await connection.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('heading', { name: '嵌入器 Embedder', exact: true })).toBeVisible()
  await model.getByRole('button', { name: '删除', exact: true }).click()
  await connection.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(model).toHaveCount(0)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '向量存储', exact: true }).click()
  await page.getByRole('button', { name: '添加 Qdrant 连接', exact: true }).click()
  await connection.getByLabel('连接名称', { exact: true }).fill('页面配置验收连接')
  await connection.getByLabel('服务地址', { exact: false }).fill('http://127.0.0.1:1')
  await connection.getByLabel('API Key', { exact: true }).fill('e2e-vector-key')
  await connection.getByRole('button', { name: '保存连接', exact: true }).click()
  await expect(connection).not.toBeVisible()
  const vector = page.getByRole('row').filter({ hasText: '页面配置验收连接' })
  await expect(vector).toContainText('agent_knowledge')
  await page.reload()
  await expect(vector).toContainText('agent_knowledge')
  await vector.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(connection.getByLabel('API Key', { exact: true })).toHaveValue('e2e-vector-key')
  await connection.getByLabel('API Key', { exact: true }).fill('e2e-updated-vector-key')
  await connection.getByRole('button', { name: '保存连接', exact: true }).click()
  await expect(connection).not.toBeVisible()
  await page.reload()
  await vector.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(connection.getByLabel('API Key', { exact: true })).toHaveValue('e2e-updated-vector-key')
  await connection.getByLabel('API Key', { exact: true }).fill('')
  await connection.getByRole('button', { name: '保存连接', exact: true }).click()
  await expect(connection).not.toBeVisible()
  await expect(vector).toContainText('未配置')
  await vector.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(connection.getByLabel('API Key', { exact: true })).toHaveValue('')
  await connection.getByRole('button', { name: '取消', exact: true }).click()
  await vector.getByRole('button', { name: '删除', exact: true }).click()
  await connection.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(vector).toHaveCount(0)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '知识库', exact: true }).click()
  await page.getByRole('button', { name: '新建知识库', exact: true }).click()
  const form = page.getByRole('dialog')
  await form.getByLabel('知识库名称', { exact: true }).fill('航星项目资料')
  await form.getByLabel('描述', { exact: true }).fill('浏览器真实验收，含独有事实')
  await form.getByText('高级配置', { exact: true }).click()
  await form.getByLabel('索引能力', { exact: false }).selectOption('keyword')
  await form.getByRole('button', { name: '创建知识库', exact: true }).click()
  await expect(page.getByRole('heading', { name: '航星项目资料', exact: true })).toBeVisible()
  const detailURL = page.url()

  await page.getByRole('button', { name: '添加文档', exact: true }).click()
  await form.getByRole('tab', { name: '手动输入', exact: true }).click()
  await form.getByLabel('文档标题', { exact: true }).fill('航星计划审批规则')
  await form.getByLabel('正文内容', { exact: true }).fill('航星计划的审批人是林沐，周二上午九点在青禾会议室进行评审。')
  await form.getByRole('button', { name: '添加并处理', exact: true }).click()
  const manual = page.getByRole('row').filter({ hasText: '航星计划审批规则' })
  await expect(manual).toContainText('已完成', { timeout: 20_000 })
  await page.reload()
  await expect(manual).toContainText('已完成')
  await manual.getByRole('button', { name: '查看分块', exact: true }).click()
  await expect(form).toContainText('林沐')
  await form.getByRole('button', { name: '编辑', exact: true }).first().click()
  await form.getByLabel('分块 1 内容', { exact: true }).fill('航星计划的审批人是许澄，周三下午两点在白鹭会议室进行评审。')
  await form.getByRole('button', { name: '保存分块', exact: true }).click()
  await expect(form).toContainText('分块已保存')
  await form.getByRole('button', { name: '关闭弹窗', exact: true }).click()
  await expect(manual).toContainText('已完成', { timeout: 20_000 })
  await page.getByRole('tab', { name: '检索测试', exact: true }).click()
  await page.getByLabel('检索内容', { exact: true }).fill('航星')
  await page.getByRole('button', { name: '开始检索', exact: true }).click()
  const result = page.locator('.knowledge-result')
  await expect(result).toContainText('许澄')
  await expect(result).not.toContainText('林沐')

  await page.getByRole('tab', { name: '文档管理', exact: true }).click()
  await page.getByRole('button', { name: '添加文档', exact: true }).click()
  await form.getByLabel('选择文件', { exact: true }).setInputFiles({ name: '星河仓储.md', mimeType: 'text/markdown', buffer: Buffer.from('# 星河仓储\n星河仓储的备用仓位为 B-731，由钟遥负责。') })
  await form.getByRole('button', { name: '上传并处理', exact: true }).click()
  const uploaded = page.getByRole('row').filter({ hasText: '星河仓储.md' })
  await expect(uploaded).toContainText('已完成', { timeout: 20_000 })
  const downloadEvent = page.waitForEvent('download')
  await uploaded.getByRole('button', { name: '下载原件', exact: true }).click()
  const downloaded = await downloadEvent
  expect(downloaded.suggestedFilename()).toBe('星河仓储.md')
  expect(await downloaded.failure()).toBeNull()

  await manual.getByRole('button', { name: '删除', exact: true }).click()
  await form.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(manual).toHaveCount(0)
  await page.getByRole('tab', { name: '检索测试', exact: true }).click()
  await page.getByLabel('检索内容', { exact: true }).fill('航星')
  await page.getByRole('button', { name: '开始检索', exact: true }).click()
  await expect(page.getByText('未检索到匹配内容', { exact: true })).toBeVisible()
  await page.getByLabel('检索内容', { exact: true }).fill('星河')
  await page.getByRole('button', { name: '开始检索', exact: true }).click()
  await expect(result).toContainText('B-731')
  await page.reload()
  await expect(page).toHaveURL(detailURL)
  await expect(uploaded).toContainText('已完成')
  await page.getByRole('button', { name: '删除知识库', exact: true }).click()
  await form.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page).toHaveURL(`${origin}/knowledge`)
  await page.reload()
  await expect(page.getByRole('link').filter({ hasText: '航星项目资料' })).toHaveCount(0)
})
