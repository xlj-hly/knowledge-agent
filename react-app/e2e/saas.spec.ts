    await wechat.getByLabel('小程序 AppID', { exact: true }).fill('wx1234567890abcdef')
    await wechat.getByLabel('小程序 AppSecret', { exact: false }).fill('0123456789abcdef0123456789abcdef')
    await wechat.getByRole('button', { name: '保存小程序配置' }).click()
    await expect(wechat).not.toBeVisible()
    await tenantRow.getByRole('button', { name: '小程序配置', exact: true }).click()
    await expect(wechat.getByLabel('小程序 AppID', { exact: true })).toHaveValue('wx1234567890abcdef')
    await expect(wechat.getByLabel('小程序 AppSecret', { exact: false })).toHaveValue('0123456789abcdef0123456789abcdef')
    await wechat.getByLabel('小程序 AppSecret', { exact: false }).fill('abcdef0123456789abcdef0123456789')
    await wechat.getByRole('button', { name: '保存小程序配置' }).click()
